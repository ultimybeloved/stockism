'use strict';

// Uploads the Discord ladder board tiles (public/pins/ladder, drawn by
// scripts/pixel-ladder.cjs) as APPLICATION emojis named lad_<tile>, and writes
// their markup into functions/src/shared/constants/ladderEmojis.ts, which
// discord/ladderBoard.ts reads.
//
//   node scripts/sync-ladder-emojis.cjs                      # show what's uploaded
//   node scripts/sync-ladder-emojis.cjs --upload --write     # upload missing ones, write the IDs
//   node scripts/sync-ladder-emojis.cjs --replace odd_a,odd_b --upload --write
//                                                            # re-upload redrawn tiles
//
// Same conversion and reasoning as sync-pixel-emojis.cjs. Deploy
// discordInteractions after --write for the IDs to take effect.

const fs = require('fs');
const path = require('path');
const { readBotToken, discord, getApp } = require('./discord-api.cjs');
const { svgGrid, gridToPng } = require('./sync-pixel-emojis.cjs');

const ROOT = path.join(__dirname, '..');
const TILE_DIR = path.join(ROOT, 'public', 'pins', 'ladder');
const OUT_PATH = path.join(ROOT, 'functions', 'src', 'shared', 'constants', 'ladderEmojis.ts');

const listAppEmojis = async (token, appId) =>
  ((await discord(token, `/applications/${appId}/emojis`)) || {}).items || [];

async function main() {
  const upload = process.argv.includes('--upload');
  const write = process.argv.includes('--write');
  const replaceArg = process.argv[process.argv.indexOf('--replace') + 1];
  const replace = new Set(process.argv.includes('--replace') ? replaceArg.split(',') : []);
  const tiles = fs
    .readdirSync(TILE_DIR)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();

  const token = readBotToken();
  const app = await getApp(token);
  console.log(`App: ${app.name} (${app.id})`);
  let appEmojis = await listAppEmojis(token, app.id);

  if (upload) {
    for (const tile of tiles) {
      const name = `lad_${tile}`;
      const existing = appEmojis.find((e) => e.name === name);
      if (existing && replace.has(tile)) {
        await discord(token, `/applications/${app.id}/emojis/${existing.id}`, { method: 'DELETE' });
        console.log(`  - ${name} deleted for re-upload`);
      } else if (existing) {
        continue;
      }
      const png = gridToPng(svgGrid(path.join(TILE_DIR, `${tile}.svg`)));
      await discord(token, `/applications/${app.id}/emojis`, {
        method: 'POST',
        body: JSON.stringify({ name, image: `data:image/png;base64,${png.toString('base64')}` }),
      });
      console.log(`  + ${name} uploaded`);
    }
    appEmojis = await listAppEmojis(token, app.id);
  }

  const resolved = {};
  const missing = [];
  for (const tile of tiles) {
    const e = appEmojis.find((x) => x.name === `lad_${tile}`);
    if (e) resolved[tile] = `<:${e.name}:${e.id}>`;
    else missing.push(tile);
  }
  console.log(`${Object.keys(resolved).length} of ${tiles.length} tiles uploaded.`);
  if (missing.length) console.log(`Missing: ${missing.join(', ')} (run with --upload)`);

  if (write) {
    if (missing.length) throw new Error('Not writing with tiles missing; run with --upload first.');
    const body = Object.entries(resolved)
      .map(([tile, markup]) => `  ${tile}: '${markup}',`)
      .join('\n');
    fs.writeFileSync(
      OUT_PATH,
      `// GENERATED by scripts/sync-ladder-emojis.cjs: the Discord ladder board tiles,\n` +
        `// uploaded as application emojis. Never edit by hand; re-run the script.\n` +
        `export const LADDER_EMOJIS = {\n${body}\n} as const;\n\n` +
        `export type LadderTile = keyof typeof LADDER_EMOJIS;\n`,
    );
    console.log(`Wrote ${path.relative(ROOT, OUT_PATH)} (deploy discordInteractions to take effect).`);
  }
}

main().catch((err) => {
  console.error(`\n${err.message}`);
  process.exit(1);
});
